const reverseTranslations = new Map(Object.entries(translations).map(([english, tagalog]) => [tagalog, english]))
const attributesToTranslate = ['placeholder', 'title', 'aria-label']

function translateValue(value: string, language: Language) {
  if (language === 'en') return reverseTranslations.get(value.trim()) ? preserveWhitespace(value, reverseTranslations.get(value.trim())!) : value
  const translated = translations[value.trim()]
  return translated ? preserveWhitespace(value, translated) : value
}

function preserveWhitespace(original: string, translated: string) {
  const leading = original.match(/^\s*/)?.[0] ?? ''
  const trailing = original.match(/\s*$/)?.[0] ?? ''
  return `${leading}${translated}${trailing}`
}

function translateNode(node: Node, language: Language) {
  if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
    const next = translateValue(node.nodeValue, language)
    if (next !== node.nodeValue) node.nodeValue = next
  }
  if (node.nodeType === Node.ELEMENT_NODE) {
    const element = node as Element
    for (const attribute of attributesToTranslate) {
      const value = element.getAttribute(attribute)
      if (!value) continue
      const next = translateValue(value, language)
      if (next !== value) element.setAttribute(attribute, next)
    }
    for (const child of Array.from(node.childNodes)) translateNode(child, language)
  }
}

export function applyLanguage(root: HTMLElement, language: Language) {
  const locale = language === 'tl' ? 'fil' : 'en'
  root.lang = locale
  document.documentElement.lang = locale
  translateNode(root, language)
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'attributes') translateNode(record.target, language)
      else if (record.type === 'characterData') translateNode(record.target, language)
      else for (const node of Array.from(record.addedNodes)) translateNode(node, language)
    }
  })
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attributesToTranslate })
  return () => observer.disconnect()
}
